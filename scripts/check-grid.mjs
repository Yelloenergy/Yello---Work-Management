import assert from 'node:assert/strict';
import {timing,fromSydney,addCalendarDays,HOUR,validateRecord} from '../public/grid-model.js';
const proof='2026-11-01T00:00:00.000Z';
const record={fields:{'Sales Date':'2026-10-01','Grid Status':'Grid Waiting','Meter Applied':'Waiting','Payment Done':'Done','Payment Proof Received':proof},files:[{group:'payment'}]};
const at=h=>Date.parse(proof)+h*HOUR;
assert.equal(timing(record,at(47.99)).meter.late,false);
assert.equal(timing(record,at(48)).meter.late,true);
assert.equal(timing(record,at(71.99)).meter.escalated,false);
assert.equal(timing(record,at(72)).meter.escalated,true);
const submitted=structuredClone(record);submitted.fields['Meter Applied']='Applied';submitted.fields['Meter Date + Time']=new Date(at(47)).toISOString();
assert.equal(timing(submitted,at(100)).meter.late,false);assert.equal(timing(submitted,at(100)).meter.escalated,false);
submitted.fields['Meter Date + Time']=new Date(at(50)).toISOString();assert.equal(timing(submitted,at(100)).meter.late,true);
const noProof=structuredClone(record);noProof.files=[];assert.equal(timing(noProof,at(100)).meter.due,null);assert.ok(validateRecord(noProof).length);
const notRequired=structuredClone(record);notRequired.fields['Meter Applied']='Not Required';assert.equal(timing(notRequired,at(100)).meter.late,false);
const dst=fromSydney('2026-10-01T12:00');assert.equal(addCalendarDays(dst,10),'2026-10-11T01:00:00.000Z');
assert.equal((Date.parse(addCalendarDays(dst,10))-Date.parse(dst))/HOUR,239);
const completed=structuredClone(record);completed.fields['Approval Date']=addCalendarDays(fromSydney('2026-10-01'),9);
assert.equal(timing(completed,at(100)).grid.late,false);
const invalid=structuredClone(submitted);invalid.fields['Meter Date + Time']=null;assert.ok(validateRecord(invalid).length);
console.log('Grid checks passed: 48h deadline, 72h escalation, completed timing, missing proof, exemptions and Sydney calendar days.');
